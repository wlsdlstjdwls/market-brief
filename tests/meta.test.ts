/**
 * 작성 메모 걷어내기 회귀.
 *
 * 루틴이 검색에 실패한 날 원고에 "미확인", "이번 검색에서 확인하지 못했다" 같은 말이
 * 남고, 그게 화면과 텔레그램에 그대로 나갔다(2026-10-22 사용자 지적).
 * 예문은 전부 2026-10 실제 회차에서 가져왔다.
 */
import { strict as assert } from "node:assert";
import { test } from "node:test";
import { hasMeta, stripMeta, stripMetaTitle } from "../src/lib/meta";

test("메모뿐인 줄은 통째로 지운다", () => {
  for (const line of [
    "- 환율, 원자재: 미확인.",
    "- 외국인, 기관 순매수 TOP10, 동시 순매수, 5거래일 수급: **데이터 미확인.**",
    "> **작성 환경 제약:** 기사 본문 열람(WebFetch)이 DNS 실패(ENOTFOUND)로 막혀 검색 결과 요약만 근거로 했다.",
    "> **거래일 확인:** KST 2026-10-22 목요일. `market-brief/data/krx-holidays.json`의 10월 휴장일은 10/05, 10/09뿐이라 거래일이다.",
    "- **10/1(현지) 마감: 데이터 미확인.** 검색에서 찾은 기사들은 다른 연도 수치여서 쓰지 않았다.",
  ]) {
    assert.equal(stripMeta(line), "", line);
  }
});

test("뉴스 문장은 남기고 메모 문장만 뺀다", () => {
  assert.equal(
    stripMeta(
      "장기금리 급등이 미 증시 하락의 직접 원인이다. 10/8 종가, 원/달러 환율은 이번 검색에서 확인하지 못했다.",
    ),
    "장기금리 급등이 미 증시 하락의 직접 원인이다.",
  );
  assert.equal(
    stripMeta(
      "- **결론: 코스피 약세, 코스닥 약보합.** 종가, 등락률은 미확인. 어제 종가는 코스피 6,941.39(-0.89%)였다.",
    ),
    "- **결론: 코스피 약세, 코스닥 약보합.** 어제 종가는 코스피 6,941.39(-0.89%)였다.",
  );
});

test("메모 괄호만 떼고 문장은 남긴다", () => {
  assert.equal(
    stripMeta("코스피 6,934.45(-0.99%), 코스닥 916.84(+2.64%)(14:52 기준, 종가 미확인)."),
    "코스피 6,934.45(-0.99%), 코스닥 916.84(+2.64%).",
  );
  assert.equal(
    stripMeta("분기말 리밸런싱 효과가 끝나 매도 강도가 줄 가능성이 있다(추정)."),
    "분기말 리밸런싱 효과가 끝나 매도 강도가 줄 가능성이 있다.",
  );
});

test("숫자에 붙은 추정은 문장째 버린다 — 꼬리표만 떼면 확정치로 읽힌다", () => {
  assert.equal(stripMeta("- 어제 한국 마감: 코스피 6,803.90(-1.98%, 추정)."), "");
});

test("카드 제목", () => {
  assert.equal(
    stripMetaTitle("연준 의사록 — 연말 추가 인상 가능성 시사(검색 요약)"),
    "연준 의사록 — 연말 추가 인상 가능성 시사",
  );
  assert.equal(stripMetaTitle("국제유가 — 9/29 WTI 89.38달러 이후 9/30 수치 미확인"), "");
});

test("멀쩡한 뉴스는 건드리지 않는다", () => {
  for (const s of [
    "한국은행 오늘(22일) 금통위 — 3.00% 동결 유력, 11월 인상 시사 주목",
    "10월 1~20일 수출 616.1억달러(+105.4%), 반도체 275.2억달러(+222.5%) 역대 최대",
    "미 연준은 금리 인상을 보류했다.",
    "개별 수주, 실적 뉴스 확인 필요",
    "- 수출: 반도체 비중 47.8%.\n\n- 금리: 10년물 5.12%.",
  ]) {
    assert.equal(stripMeta(s), s);
    assert.equal(hasMeta(s), false);
  }
});
